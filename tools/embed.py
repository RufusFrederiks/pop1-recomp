#!/usr/bin/env python3
"""Pack work/files/ (your extracted game files) into src/gen/embedded.c, for
the single-file Windows build (tools/cross-windows.sh --standalone).

    python tools/embed.py

src/gen/ is gitignored: like the lifted code, this is derived from your own
copy of the game and stays on your machine."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FILES = ROOT / "work" / "files"

def main():
    rows = (FILES / "files.txt").read_bytes().decode("mac_roman").splitlines()
    paths = ["files/files.txt"]
    for r in rows:
        if r.startswith("#"): continue
        f = r.split("\t")
        for p in (f[3], f[5]):
            if p != "-": paths.append(p)
    out = ["/* generated by tools/embed.py from work/files -- do not edit, do not commit */",
           "#include <stdint.h>",
           "typedef struct { const char *path; const uint8_t *data; unsigned len; } PopEmbedded;"]
    total = 0
    for i, p in enumerate(paths):
        data = (ROOT / "work" / p).read_bytes(); total += len(data)
        body = ",".join(str(b) for b in data)
        out.append(f"static const uint8_t f{i}[{max(len(data),1)}] = {{{body or '0'}}};")
    out.append("const PopEmbedded pop_embedded[] = {")
    for i, p in enumerate(paths):
        out.append(f'  {{"{p}", f{i}, {len((ROOT / "work" / p).read_bytes())}u}},')
    out.append("};")
    out.append(f"const int pop_n_embedded = {len(paths)};")
    (ROOT / "src" / "gen" / "embedded.c").write_text("\n".join(out) + "\n")
    print(f"{len(paths)} files, {total} bytes -> src/gen/embedded.c")

if __name__ == "__main__":
    main()
